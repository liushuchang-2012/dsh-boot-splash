#!/usr/bin/env node
/* Builds the two artefacts from the readable sources:
 *   src/scene.css      stylesheet
 *   src/scene.html     markup
 *   src/timeline.js    mountSplash() — the whole film as render(t)
 *   dev/logo-data.js   authentic brand vectors
 *
 * Outputs:
 *   src/splash.js      the framework-free bundle boot.html previews in dev/
 *   client.js          the module the shell loads via __ModuleLoader__.load()
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, p), "utf8");
const indent = (text, pad) => text.split("\n").map((l) => (l ? pad + l : l)).join("\n");

const CSS = read("src/scene.css").trim();
const HTML = read("src/scene.html").trim();
const TIMELINE = read("src/timeline.js").trim();

/* the brand vectors live in a dev/ helper that also drives the contact sheets */
const logoData = read("dev/logo-data.js");
const start = logoData.indexOf("{");
const end = logoData.lastIndexOf("}");
if (start < 0 || end < 0) throw new Error("logo-data.js: no object literal found");
const LOGO = logoData.slice(start, end + 1);

/* ---------------------------------------------------------------- src/splash.js */
const splash = `/* dsh-boot-splash — GENERATED by build.mjs. Edit src/scene.css, src/scene.html
   and src/timeline.js instead; this file only exists so dev/boot.html can preview
   the exact code the plugin ships. */
(function (global) {
  var CSS = ${JSON.stringify(CSS)};
  var HTML = ${JSON.stringify(HTML)};

${indent(TIMELINE, "  ")}

  global.__DSH_SPLASH__ = { CSS: CSS, HTML: HTML, mountSplash: mountSplash };
})(typeof window !== "undefined" ? window : globalThis);
`;
writeFileSync(join(root, "src/splash.js"), splash);

/* -------------------------------------------------------------------- client.js */
const client = `/* dsh-boot-splash — client half. GENERATED by build.mjs from src/scene.css,
 * src/scene.html, src/timeline.js and dev/logo-data.js. Do not edit by hand.
 */
window.__ModuleLoader__.load({
  id: "dsh-boot-splash",
  factory(require) {
    var React = require("react");
    var h = React.createElement;

    /* authentic brand vectors: whale mark, wordmark, plate, HARNESS glyphs */
    var LOGO = ${LOGO};

    var CSS = ${JSON.stringify(CSS)};
    var HTML = ${JSON.stringify(HTML)};

${indent(TIMELINE, "    ")}

    var playedThisLoad = false;

    function Overlay() {
      var hostRef = React.useRef(null);
      var handleRef = React.useRef(null);
      var state = React.useState(false);
      var gone = state[0];
      var setGone = state[1];

      React.useEffect(function () {
        if (playedThisLoad || !hostRef.current) { setGone(true); return; }
        playedThisLoad = true;
        handleRef.current = mountSplash(hostRef.current, LOGO, {
          onDone: function () { setGone(true); },
        });
        return function () {
          if (handleRef.current) { handleRef.current.destroy(); handleRef.current = null; }
        };
      }, []);

      if (gone) return null;
      return h("div", {
        ref: hostRef,
        className: "dsh-boot-splash",
        "aria-hidden": "true",
        onPointerDown: function () {
          if (handleRef.current) handleRef.current.skip();
        },
      });
    }

    return {
      inject: ["slots"],
      apply: function (ctx) {
        ctx.slots.inject("shell.overlay", function () {
          return ctx.slots.register({
            name: "shell.overlay",
            id: "dsh-boot-splash",
            order: -1000,
            label: function () { return "Boot splash"; },
          }, Overlay);
        });
        ctx.effect(function () {
          var style = document.createElement("style");
          style.id = "dsh-boot-splash-host";
          style.textContent = ".dsh-boot-splash{position:fixed;inset:0;z-index:2147483000;background:#fff;overflow:hidden}";
          document.head.appendChild(style);
          return function () { style.remove(); };
        });
      },
    };
  },
});
`;
writeFileSync(join(root, "client.js"), client);

console.log("src/splash.js", splash.length, "bytes");
console.log("client.js", client.length, "bytes");
