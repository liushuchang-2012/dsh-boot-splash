#!/usr/bin/env node
/* Builds client.js — the single file the shell loads through
   window.__ModuleLoader__.load({ id, factory }).
   Inputs: src/splash.js (the animation, framework-free) and
   dev/logo-data.js (the authentic brand vectors). */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, p), "utf8");

const splash = read("src/splash.js");
const logoData = read("dev/logo-data.js");

const start = logoData.indexOf("{");
const end = logoData.lastIndexOf("}");
if (start < 0 || end < 0) throw new Error("logo-data.js: no object literal found");
const logo = logoData.slice(start, end + 1);

const out = `/* dsh-boot-splash — client half.
 * Generated by build.mjs from src/splash.js + dev/logo-data.js. Do not edit by hand:
 * the wordmark, the timeline and the overlay mount all live in those sources.
 */
window.__ModuleLoader__.load({
  id: "dsh-boot-splash",
  factory(require) {
    var React = require("react");
    var h = React.createElement;

    /* ---- authentic brand vectors (whale mark, wordmark, plate, HARNESS glyphs) ---- */
    var LOGO = ${logo};

    /* ---- the animation ---- */
${splash
  .split("\n")
  .map((line) => (line ? "    " + line : line))
  .join("\n")}
    var SPLASH = window.__DSH_SPLASH__;
    var playedThisLoad = false;

    function Overlay() {
      var hostRef = React.useRef(null);
      var handleRef = React.useRef(null);
      var state = React.useState(false);
      var gone = state[0];
      var setGone = state[1];

      React.useEffect(function () {
        if (playedThisLoad || !hostRef.current) { setGone(true); return; }
        playedThisLoad = true;
        handleRef.current = SPLASH.mountSplash(hostRef.current, LOGO, {
          onDone: function () { setGone(true); },
        });
        return function () {
          if (handleRef.current) { handleRef.current.destroy(); handleRef.current = null; }
        };
      }, []);

      if (gone) return null;
      return h("div", {
        ref: hostRef,
        className: "dsh-boot-splash",
        "aria-hidden": "true",
        onPointerDown: function () {
          if (handleRef.current) handleRef.current.skip();
        },
      });
    }

    return {
      inject: ["slots"],
      apply: function (ctx) {
        ctx.slots.inject("shell.overlay", function () {
          return ctx.slots.register({
            name: "shell.overlay",
            id: "dsh-boot-splash",
            order: -1000,
            label: function () { return "Boot splash"; },
          }, Overlay);
        });
        ctx.effect(function () {
          var style = document.createElement("style");
          style.id = "dsh-boot-splash-host";
          style.textContent = ".dsh-boot-splash{position:fixed;inset:0;z-index:2147483000;background:#fff;overflow:hidden}";
          document.head.appendChild(style);
          return function () { style.remove(); };
        });
      },
    };
  },
});
`;
writeFileSync(join(root, "client.js"), out);
console.log("client.js", out.length, "bytes");
